/**
 * The load test's report (e2e/load/run.sh): results.json (load.mjs), stats.tsv (docker stats
 * every 5 s: epoch ms, container, memory, CPU) and machine.json, as Markdown in $REPORT plus
 * a compact table on stdout.
 *
 * Memory is what `docker stats` shows (the container's cgroup usage without its reclaimable
 * page cache, close to the working set Kubernetes reports). "Production stack" leaves MinIO
 * out (production uses S3) and adds the scheduler, which the e2e stack does not run, at the
 * queue worker's idle size (the same PHP process, mostly asleep).
 */
import { readFileSync, writeFileSync } from 'node:fs'

const read = (path) => readFileSync(path, 'utf8')
const result = JSON.parse(read('/in/results.json'))
const machine = JSON.parse(read('/in/machine.json'))
const profile = process.env.PROFILE ?? 'full'

// The node around the pods (docs/runbook.md §2): k3s itself, measured on an idle k3s v1.36.5
// node running the production chart (server, containerd and shims, CoreDNS, metrics-server,
// local-path: 856 MiB working set minus 202 MiB of Slax pods), plus Ubuntu, Tailscale and
// Caddy (an estimate). A budget for growth (more PHP-FPM workers, PostgreSQL's shared
// buffers filling up over days). t4g.small: 2048 MiB, ≈ 1946 MiB usable by processes.
const K3S_MIB = 655
const OS_LOW_MIB = 250
const OS_HIGH_MIB = 300
const GROWTH_MIB = 100
const NODE_LOW_MIB = K3S_MIB + OS_LOW_MIB
const NODE_HIGH_MIB = K3S_MIB + OS_HIGH_MIB
const INSTANCE_MIB = 2048
const USABLE_MIB = 1946

const UNITS = { B: 1 / 1048576, KiB: 1 / 1024, kB: 1 / 1024, MiB: 1, MB: 1, GiB: 1024, GB: 1024 }
function mib(text) {
  const match = /^([\d.]+)\s*([A-Za-z]+)$/.exec(text.trim())
  return match ? Number(match[1]) * (UNITS[match[2]] ?? NaN) : NaN
}
function service(container) {
  return container.replace(/^slax-load-/, '').replace(/-\d+$/, '')
}

const samples = read('/in/stats.tsv')
  .split('\n')
  .filter(Boolean)
  .map((line) => {
    const [at, container, memory, cpu] = line.split('\t')
    return { at: Number(at), service: service(container), mib: mib(memory.split('/')[0]), cpu: Number.parseFloat(cpu) }
  })
  .filter((sample) => Number.isFinite(sample.mib))

const { send_started_at: start, send_ended_at: end } = result.phases
const windowEnd = end + result.config.drain_seconds * 1000
const idle = samples.filter((s) => s.at < start)
const busy = samples.filter((s) => s.at >= start && s.at <= windowEnd)
const services = [...new Set(samples.map((s) => s.service))].sort()

const mean = (values) => (values.length === 0 ? NaN : values.reduce((a, b) => a + b, 0) / values.length)
const max = (values) => (values.length === 0 ? NaN : Math.max(...values))
const fmt = (value, digits = 0) => (Number.isFinite(value) ? value.toFixed(digits) : 'n/a')

const perService = services.map((name) => {
  const idleOf = idle.filter((s) => s.service === name)
  const busyOf = busy.filter((s) => s.service === name)
  return {
    name,
    idle: idleOf.at(-1)?.mib ?? NaN,
    mean: mean(busyOf.map((s) => s.mib)),
    peak: max(busyOf.map((s) => s.mib)),
    cpuMean: mean(busyOf.map((s) => s.cpu)),
    cpuPeak: max(busyOf.map((s) => s.cpu)),
  }
})

// Totals per sampling round (samples of one round share a docker stats call, within a second).
function totals(list, keep) {
  const rounds = new Map()
  for (const s of list) {
    if (!keep(s.service)) continue
    const key = Math.round(s.at / 2000)
    rounds.set(key, (rounds.get(key) ?? 0) + s.mib)
  }
  return [...rounds.values()]
}
const all = () => true
const prodLike = (name) => name !== 'minio'
const peakAll = max(totals(busy, all))
const peakProd = max(totals(busy, prodLike))
const idleProd = max(totals(idle, prodLike))
const scheduler = perService.find((s) => s.name === 'queue')?.idle ?? 80
const stackProd = peakProd + scheduler
const low = stackProd + GROWTH_MIB + NODE_LOW_MIB
const high = stackProd + GROWTH_MIB + NODE_HIGH_MIB

const r = result
const d = r.deliveries
const post = r.http.by_kind['post-message']?.latency_ms ?? {}
const pass = d.lost === 0 && d.duplicates === 0 && r.http.errors === 0 && r.error_count === 0 && r.messages.accepted === r.messages.attempted && r.websocket.closed_before_end === 0

const lines = []
const out = (line = '') => lines.push(line)
out(`# Load test results${profile === 'smoke' ? ' (smoke)' : ''}`)
out()
out(`Generated by \`make load${profile === 'smoke' ? '-smoke' : ''}\` (e2e/load/) on ${r.started_at.slice(0, 16).replace('T', ' ')} UTC. ` +
  'The stack is the local end-to-end one (Docker Compose, `APP_ENV=e2e`, the development PHP image), not k3s: see "From Compose to t4g.small" below and docs/runbook.md §2.')
out()
out('## Machine')
out()
out(`${machine.cpu}, ${machine.threads} threads, ${machine.memory_gib} GiB RAM, ${machine.os} (kernel ${machine.kernel}, ${machine.arch}), Docker ${machine.docker}. ` +
  'The load generator runs on the same machine as the stack.')
out()
out('## Load')
out()
out('| | |')
out('|---|---|')
out(`| Clients (WebSocket, signed in, subscribed to the channel and the workspace presence, heartbeat every 25 s) | ${r.config.clients} |`)
out(`| Senders (REST \`POST /api/v1/channels/{id}/messages\`) | ${r.config.senders} |`)
out(`| Target rate × duration | ${r.config.rate_per_second} messages/s × ${r.config.seconds} s |`)
out(`| Messages accepted / attempted | ${r.messages.accepted} / ${r.messages.attempted} (${r.messages.achieved_rate_per_second}/s achieved) |`)
out(`| Deliveries received / expected (every message to every client) | ${d.delivered} / ${d.expected} |`)
out(`| Lost / duplicated | ${d.lost} / ${d.duplicates} |`)
out(`| Delivery latency, POST sent → message on the socket (p50 / p95 / p99 / max) | ${d.latency_ms.p50} / ${d.latency_ms.p95} / ${d.latency_ms.p99} / ${d.latency_ms.max} ms |`)
out(`| POST latency (p50 / p95 / p99) | ${post.p50} / ${post.p95} / ${post.p99} ms |`)
out(`| HTTP requests / errors (all kinds) | ${r.http.requests} / ${r.http.errors} (${fmt(r.http.error_rate * 100, 2)} %) |`)
out(`| WebSockets closed during the run | ${r.websocket.closed_before_end} |`)
out(`| Sign-in of all clients / subscription of all clients | ${r.phases.sign_in_seconds} s / ${r.phases.subscribe_seconds} s |`)
out(`| **Verdict** (no loss, no duplicate, no error) | **${pass ? 'PASS' : 'FAIL'}** |`)
out()
out('## Containers (docker stats every 5 s)')
out()
out('Memory in MiB; CPU in % of one core. "Idle": the last sample before the first message; mean and peak: from the first message to the end of the delivery wait.')
out()
out('| Service | Idle MiB | Mean MiB | Peak MiB | CPU mean % | CPU peak % |')
out('|---|---:|---:|---:|---:|---:|')
for (const s of perService) out(`| ${s.name} | ${fmt(s.idle)} | ${fmt(s.mean)} | ${fmt(s.peak)} | ${fmt(s.cpuMean, 1)} | ${fmt(s.cpuPeak, 1)} |`)
out(`| **All containers (peak of the sums)** | | | **${fmt(peakAll)}** | | |`)
out(`| **Without MinIO (production uses S3)** | ${fmt(idleProd)} | | **${fmt(peakProd)}** | | |`)
out()
out('## From Compose to t4g.small (2 GiB)')
out()
out('An estimate, not a measurement: Compose is not k3s, the e2e stack runs the development PHP image (not the production slax-app build and its PHP-FPM settings) with `APP_DEBUG=true`, PostgreSQL and Redis with their default settings, and no scheduler. Memory per process is of the same order on both, and `docker stats` and the kubelet both count the working set (usage without reclaimable cache).')
out()
out('| | MiB |')
out('|---|---:|')
out(`| Slax under load, without MinIO (peak, measured) | ${fmt(peakProd)} |`)
out(`| + scheduler (not in the e2e stack; the queue worker's idle size) | ${fmt(scheduler)} |`)
out(`| = Slax pods | ${fmt(stackProd)} |`)
out(`| + a budget for growth (more PHP-FPM workers, PostgreSQL's buffers filling up) | ${GROWTH_MIB} |`)
out(`| + k3s itself (measured idle on k3s v1.36.5 with the production chart) | ${K3S_MIB} |`)
out(`| + Ubuntu, Tailscale, Caddy (estimate) | ${OS_LOW_MIB} to ${OS_HIGH_MIB} |`)
out(`| = the instance | ${fmt(low)} to ${fmt(high)} |`)
out(`| Share of the instance's ${INSTANCE_MIB} MiB (brief: < 80 % = ${Math.round(INSTANCE_MIB * 0.8)} MiB) | ${fmt((low / INSTANCE_MIB) * 100)} % to ${fmt((high / INSTANCE_MIB) * 100)} % |`)
out(`| Left of ≈ ${USABLE_MIB} MiB usable, for page cache and spikes | ${fmt(USABLE_MIB - high)} to ${fmt(USABLE_MIB - low)} |`)
out()
writeFileSync(process.env.REPORT, lines.join('\n'))

// Compact summary on stdout.
const row = (label, value) => console.log(`  ${label.padEnd(34)} ${value}`)
console.log(`Load test (${profile}): ${pass ? 'PASS' : 'FAIL'}`)
row('messages accepted', `${r.messages.accepted}/${r.messages.attempted} at ${r.messages.achieved_rate_per_second}/s`)
row('deliveries (lost, duplicates)', `${d.delivered}/${d.expected} (${d.lost}, ${d.duplicates})`)
row('latency p50/p95/p99/max (ms)', `${d.latency_ms.p50} / ${d.latency_ms.p95} / ${d.latency_ms.p99} / ${d.latency_ms.max}`)
row('HTTP errors', `${r.http.errors}/${r.http.requests}`)
for (const s of perService) row(`${s.name} MiB idle/peak, CPU% peak`, `${fmt(s.idle)} / ${fmt(s.peak)}, ${fmt(s.cpuPeak, 1)}`)
row('stack peak MiB (all / without MinIO)', `${fmt(peakAll)} / ${fmt(peakProd)}`)
row('t4g.small projection', `${fmt(low)}-${fmt(high)} MiB of ${INSTANCE_MIB} (${fmt((low / INSTANCE_MIB) * 100)}-${fmt((high / INSTANCE_MIB) * 100)} %)`)
